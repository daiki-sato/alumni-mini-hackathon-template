export const GENRES = ["すべて", "ラーメン", "喫茶", "定食", "餃子", "パン", "カレー"] as const;
export type GenreFilter = (typeof GENRES)[number];
export type Genre = Exclude<GenreFilter, "すべて">;

export type TownKind = "shitamachi" | "station" | "office" | "campus" | "residential";

export type Town = {
  id: string;
  name: string;
  /** 街の種類を一言で（検索にも使う） */
  label: string;
  /** 検索で当てる別名 */
  keywords: string[];
  kind: TownKind;
  /** 街の中の区分。Shop.a はこの添字 */
  areas: [string, string, string];
  /** 世界地図での街の左上（街の中の座標は 0〜320） */
  ox: number;
  oy: number;
};

/** 街ひとつの大きさ（街の中の座標の範囲） */
export const TOWN_SIZE = 320;
export const WORLD = { w: 1400, h: 980 } as const;

export type ShopData = {
  /** 店名 */
  n: string;
  /** ジャンル */
  g: Genre;
  /** 街の中の区分（Town.areas の添字） */
  a: 0 | 1 | 2;
  /** 街の中の位置（0〜320） */
  x: number;
  y: number;
  /** 口コミ件数 */
  rv: number;
  /** 平均評価 */
  rt: number;
  /** 評価の分布(%) ★1〜★5 */
  d: [number, number, number, number, number];
  /** ここ3か月の口コミの割合 */
  rc: number;
  /** 口コミに「インスタ」「映え」が出る割合 */
  ig: number;
  /** 一人客・カップル・グループの割合（客数） */
  so: number;
  cp: number;
  gr: number;
  /** 常連の割合 */
  rg: number;
  /** 若者の割合 */
  yg: number;
  /** 店の制約 */
  cs: string[];
};

export type Shop = ShopData & {
  id: number;
  townId: string;
  /** 世界地図での位置 */
  wx: number;
  wy: number;
};

