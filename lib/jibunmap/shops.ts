const BY_TOWN: [string, number, ShopData[]][] = [
  // 灯町は ik-1 と同じ id（1〜20）にする。今日の3軒の同点時は id の小さい順なので、並びを揃えるため
  ["tomori", 1, TOMORI],
  ["minato", 101, MINATO],
  ["kasumi", 201, KASUMI],
  ["gakuen", 301, GAKUEN],
  ["sakura", 401, SAKURA],
];

const townById = new Map(TOWNS.map((t) => [t.id, t]));

export function getTown(id: string): Town {
  const t = townById.get(id);
  if (!t) throw new Error(`unknown town: ${id}`);
  return t;
}

export const SHOPS: Shop[] = BY_TOWN.flatMap(([townId, firstId, list]) => {
  const t = getTown(townId);
  return list.map((s, i) => ({
    ...s,
    id: firstId + i,
    townId,
    wx: t.ox + s.x,
    wy: t.oy + s.y,
  }));
});

const shopById = new Map(SHOPS.map((s) => [s.id, s]));

export function getShop(id: number): Shop | undefined {
  return shopById.get(id);
}

export function areaName(s: Shop): string {
  return getTown(s.townId).areas[s.a];
}

export const DEFAULT_TOWN_ID = "tomori";
